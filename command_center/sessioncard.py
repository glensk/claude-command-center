# The three mirror kinds — the ``ccc_mirror`` frontmatter value AND the folder role.
RUNNING = "running"
DONE = "done"
SESSION = "session"

# Fixed "this file is generated" banner of a mirror document (byte-stable, sits right
# after the frontmatter).
BANNER = (
    "<!-- GENERATED by ccc — export-only mirror of a command-center session. "
    "Edits are overwritten; change the session, not this file. -->"
)

# ``## Prompts`` caps (pathological-session guard): keep at most the last N prompts and
# cap the rendered body at N bytes. The most recent are kept; a note flags any trim.
# Individual prompt text is never truncated — whole older prompts are dropped instead.
PROMPTS_MAX = 200
PROMPTS_MAX_BYTES = 256 * 1024

# Per-session transcript view cache: session id → ((mtime_ns, size), view). One pass over a
# transcript yields BOTH the prompts and the session-tab segments (see :func:`view_for`);
# a session's SESSION card and its RUNNING/DONE card share it, and a long-lived process
# re-reads only a transcript whose identity moved.
VIEW_CACHE: dict[str, tuple[tuple[int, int], TranscriptView]] = {}

# ``ccc show -j`` schema: bump on a breaking change of the key set or a value's type.
SCHEMA_VERSION = 1

# The phases a card reports (``phase`` key): a future job, a live/parked session, a
# finished one. ``archived`` is reported on its own (it is orthogonal to the phase).
PHASE_DRAFT = "draft"
PHASE_RUNNING = "running"
PHASE_PARKED = "parked"
PHASE_DONE = "done"


# ---------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------
def quote(value: object) -> str:
    """A double-quoted, flat YAML scalar (escaping ``\\`` and ``"``) — round-trip safe."""
    text = "" if value is None else str(value)
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def observed_model_label(
    adapter: ClaudeAdapter, session: Session, scan: TranscriptScan | None = None
) -> str:
    """The session's OBSERVED model (from its transcript) as a ccc choice label, else "".

    *scan* is the session's transcript-scan row (the persisted fact, refreshed against
    the file by the caller when it can), so the label is read off the row and a frozen
    transcript costs one ``stat()`` instead of a tail read. Without one (a stub adapter
    with no ``scan_transcript``) it falls back to the live probe.

    ``observed_model`` is a concrete-adapter capability (like ``has_background_task`` /
    ``uses_codex_workflow``), NOT part of the ``Adapter`` protocol — probe it defensively
    so a stub adapter degrades to "". Any read error also degrades to "" (including the
    ``OSError`` the transcript readers raise — a read failure is not the fact "no model";
    see ``scan_transcript`` § Property P): a card render must never crash on a malformed
    transcript. Byte-stable: the observed model is fixed for a frozen transcript and
    changes only when the session actually switches models.
    """
    if scan is not None:
        return model_label(scan.model)
    fn = getattr(adapter, "observed_model", None)
    if fn is None:
        return ""
    try:
        return model_label(fn(session.cwd, session.session_id))
    except Exception:  # pylint: disable=broad-exception-caught
        # Contains the OSError the transcript readers raise: a read failure is not the
        # fact "no model" (see scan_transcript § Property P), and a card render must
        # never crash on it.
        return ""


def view_for(adapter: ClaudeAdapter, session: Session) -> TranscriptView:
    """The session's transcript view (prompts + session segments) from ONE pass over the file.

    Resolves the transcript once and reads it with
    :func:`command_center.transcript_cache.read_view` (parity-tested against the two walks
    ``ccc peek`` used to make), cached per process on ``(mtime_ns, size)`` — so a RUNNING
    transcript that grows re-reads while a frozen one is read once. A missing or
    unreadable transcript is the empty view: no prompts and the empty-body note.
    """
    tpath = adapter.transcript_path(session.cwd, session.session_id)
    if tpath is None:
        return transcript_cache.empty_view()
    try:
        st = tpath.stat()
    except OSError:
        return transcript_cache.empty_view()
    ident = (st.st_mtime_ns, st.st_size)
    cached = VIEW_CACHE.get(session.session_id)
    if cached is not None and cached[0] == ident:
        return cached[1]
    view = transcript_cache.read_view(tpath)
    VIEW_CACHE[session.session_id] = (ident, view)
    return view


def transcript_path(session: Session) -> Path:
    """The cwd-scoped Claude Code transcript path of *session* (may not exist)."""
    encoded = session.cwd.replace("/", "-")
    return config.claude_home() / "projects" / encoded / f"{session.session_id}.jsonl"


# ---------------------------------------------------------------------------
# prompts + AIM history sections (shared source, byte-stable)
# ---------------------------------------------------------------------------
def numbered_item(index: int, text: str, *, tag: str = "") -> list[str]:
    """One markdown ordered-list item (``N. text``) as a list of lines.

    Multi-line *text* stays one valid list item: continuation lines are indented to the
    width of the ``N. `` marker (a blank line is emitted truly blank — a valid loose-item
    paragraph break). An optional *tag* becomes a parenthesised prefix (``N. (tag) text``),
    used by the AIM-history metadata.
    """
    marker = f"{index}. "
    indent = " " * len(marker)
    head = f"{marker}({tag}) " if tag else marker
    parts = text.split("\n")
    lines = [head + parts[0]]
    lines.extend(indent + part if part.strip() else "" for part in parts[1:])
    return lines


def render_prompts(
    prompts: list[str], *, max_items: int | None = None, max_bytes: int | None = None
) -> str:
    """Numbered markdown list of the session's prompts, oldest first (matches ``ccc peek``).

    Guarded for a pathological session by two caps — at most the last *max_items* prompts
    (default :data:`PROMPTS_MAX`), and *max_bytes* of rendered body (default
    :data:`PROMPTS_MAX_BYTES`) — keeping the most recent and prefixing a ``showing last N
    of M`` note when either trims. Individual prompt text is never truncated (whole older
    prompts are dropped instead).
    """
    cap_items = PROMPTS_MAX if max_items is None else max_items
    cap_bytes = PROMPTS_MAX_BYTES if max_bytes is None else max_bytes
    total = len(prompts)
    if total == 0:
        return "(no prompts in this session yet)"
    window = prompts[-cap_items:] if total > cap_items else list(prompts)

    def _body(items: list[str]) -> str:
        lines: list[str] = []
        for index, text in enumerate(items, 1):
            # A pasted terminal snippet can open a code fence it never closes at
            # line start — which would swallow the whole rest of the file (headings,
            # the full-session wikilink …). Escape line-leading fence runs.
            lines.extend(numbered_item(index, escape_fences(text)))
        return "\n".join(lines)

    body = _body(window)
    while len(window) > 1 and len(body.encode("utf-8")) > cap_bytes:
        window = window[1:]
        body = _body(window)
    if len(window) < total:
        body = f"_showing last {len(window)} of {total} prompts_\n\n{body}"
    return body


def revisions_for(session: Session, revisions: list[AimRevision]) -> list[AimRevision]:
    """AIM history with the same pre-tracking fallback ``ccc peek`` / ``aim-history`` use.

    A session whose AIM predates history tracking has no rows; synthesise one from its live
    AIM so the ``## AIM history`` section (and the first-aim slug) are never empty.
    """
    if not revisions and session.aim:
        return [synthesize_aim_revision(session)]
    return revisions


def render_aim_history(revisions: list[AimRevision]) -> str:
    """Numbered markdown list of the AIM progression — ``1.`` oldest → ``N.`` current.

    Mirrors ``ccc aim-history``'s content choices (score, current marker, short label) but
    embeds NO per-revision timestamp, so the file's only timestamps stay ``created`` /
    ``last_response`` / ``done_at`` (the byte-stability contract).
    """
    if not revisions:
        return "(no AIM set for this session yet)"
    total = len(revisions)
    lines: list[str] = []
    for index, rev in enumerate(revisions, 1):
        tag = f"{rev.score}%" if rev.score >= 0 else "—"
        if index == total:
            tag += " · current"
        lines.extend(numbered_item(index, rev.aim, tag=tag))
        if rev.short_aim:
            lines.append(f"{' ' * len(f'{index}. ')}↳ short: {rev.short_aim}")
    return "\n".join(lines)


