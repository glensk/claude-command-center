# mirror documents (canonical, byte-stable, export-only)
# ---------------------------------------------------------------------------
def serialize_session(
    session: Session, git_base: Path, adapter: ClaudeAdapter, scan: TranscriptScan | None = None
) -> str:
    """Canonical SESSION-mirror content — the full rendered conversation.

    Same byte-stability contract as :func:`serialize_card`: pure function of the
    session's stable fields plus the transcript (mtime-cached render in ``sessionmd``);
    the only timestamps are the ISO dates of ``created_at`` / ``last_response_at``.
    *scan* is the transcript-scan row, threaded to :func:`observed_model_label`.
    """
    fm_lines = [
        "---",
        f"ccc_mirror: {quote(SESSION)}",
        f"id: {quote(display_hash(session.session_id))}",
        f"session_id: {quote(session.session_id)}",
        f"status: {quote(session.status)}",
        f"repo: {quote(cwd_to_repo(session.cwd, git_base))}",
        # OBSERVED model from the transcript (see observed_model_label); "" until a real
        # model is recorded. Same field as the running/done mirrors, for consistency.
        f"model: {quote(observed_model_label(adapter, session, scan))}",
        # OBSERVED reasoning effort (the persisted session.effort observation, no probe).
        f"effort: {quote(session.effort or '')}",
        f"transcript: {quote(str(transcript_path(session)))}",
        f"created: {quote(iso_date(session.created_at))}",
        f"last_response: {quote(iso_date(session.last_response_at))}",
    ]
    # Dependency (emitted only when set — byte-stable for dependency-less sessions).
    if session.depends_on:
        fm_lines.append(f"depends_on: {quote(session.depends_on)}")
    fm_lines.append("---")
    body = "".join(text for text, _tag in view_for(adapter, session).segments).rstrip("\n")
    frontmatter = "\n".join(fm_lines)
    return f"{frontmatter}\n\n{BANNER}\n\n{body}\n"


def serialize_card(  # noqa: PLR0913  # pylint: disable=too-many-locals,too-many-arguments,too-many-positional-arguments
    store: Store,
    session: Session,
    kind: str,
    git_base: Path,
    adapter: ClaudeAdapter,
    revisions: list[AimRevision],
    session_link: str = "",
    scan: TranscriptScan | None = None,
    *,
    prompts_max: int | None = None,
    prompts_max_bytes: int | None = None,
) -> str:
    """Canonical mirror content for *session* (``kind`` = :data:`RUNNING` / :data:`DONE`).

    Pure function of the session's stable fields plus its transcript prompts — the only
    timestamps are the ISO dates of ``created_at`` / ``last_response_at`` / ``done_at`` —
    so two calls for an unchanged session (same fields, same transcript mtime) are
    byte-identical. *revisions* is the session's pre-fetched AIM history (shared with the
    slug computation); *adapter* reads the prompt transcript. *session_link* is the
    session mirror's vault-relative path (no extension) — when set, ``## Transcript``
    opens with a ``[[…|full session]]`` wikilink to the full-conversation file. *scan* is
    the transcript-scan row, threaded to :func:`observed_model_label`. *prompts_max* /
    *prompts_max_bytes* override the ``## Prompts`` caps (see :func:`render_prompts`).
    """
    repo_label = cwd_to_repo(session.cwd, git_base)
    checked, total = store.progress(session.session_id)
    history = revisions_for(session, revisions)
    subgoals = store.list_subgoals(session.session_id)
    transcript = transcript_path(session)

    fm_lines = [
        "---",
        f"ccc_mirror: {quote(kind)}",
        f"id: {quote(display_hash(session.session_id))}",
        f"session_id: {quote(session.session_id)}",
        f"status: {quote(session.status)}",
        f"repo: {quote(repo_label)}",
        # Both links as Obsidian PROPERTIES so they sit at the very top of the note:
        # the full-session wikilink renders as a clickable chip in the properties UI.
        f"session: {quote(f'[[{session_link}|full session]]' if session_link else '')}",
        f"transcript: {quote(str(transcript))}",
        f"job_type: {quote(session.job_type or 'claude')}",
        f"llm_overseer: {quote(session.llm_overseer or DEFAULT_LLM)}",
        f"llm_exec: {quote(session.llm_exec or DEFAULT_LLM)}",
        # The OBSERVED model the session actually ran on (from the transcript) — unlike
        # llm_overseer/llm_exec, which are job-config defaults for a non-ccc-launched
        # session. "" when no real model has been recorded yet (mirrors deadline: "").
        f"model: {quote(observed_model_label(adapter, session, scan))}",
        # The OBSERVED reasoning effort captured onto the session (session.effort); "" until
        # observed. Sits right after model:, both the runtime observations.
        f"effort: {quote(session.effort or '')}",
        f"importance: {quote(session.importance)}",
        f"deadline: {quote(session.deadline or '')}",
        f"created: {quote(iso_date(session.created_at))}",
        f"last_response: {quote(iso_date(session.last_response_at))}",
        f"progress: {quote(f'{checked}/{total}')}",
        f"drift: {quote(session.drift_severity or '')}",
    ]
    # Dependency (the job this one waits on): emitted only when set, so a dependency-less
    # mirror stays byte-identical.
    if session.depends_on:
        fm_lines.append(f"depends_on: {quote(session.depends_on)}")
    if kind == DONE:
        fm_lines.append(f"done_at: {quote(iso_date(session.done_at))}")
    fm_lines.append("---")
    frontmatter = "\n".join(fm_lines)

    # The top section always shows the FIRST recorded AIM (the user's original
    # done-condition) — never the running index — plus the CURRENT revision's short
    # label once the out-of-band generator has backfilled it. The full progression
    # stays in ## AIM history.
    aim_heading = "## AIM (1)" if history else "## AIM"
    aim_body = (history[0].aim if history else session.aim or "").strip()
    current_short = history[-1].short_aim if history else ""
    if current_short:
        aim_body = f"{aim_body}\n\n↳ short (current): {current_short}"
    next_body = (session.next_step or "").strip()
    summary_body = (session.summary or "").strip()
    blocked_body = (session.blocked_on or "").strip()
    sg_body = (
        "\n".join(f"- [{'x' if sg.checked else ' '}] {sg.text}" for sg in subgoals)
        if subgoals
        else ""
    )

    aim_history_body = render_aim_history(history)
    prompts_body = render_prompts(
        view_for(adapter, session).prompts,
        max_items=prompts_max,
        max_bytes=prompts_max_bytes,
    )

    transcript_body = f"`{transcript}`\n\nResume: `c --resume {session.session_id}`"
    if session_link:
        transcript_body = f"[[{session_link}|full session]]\n\n{transcript_body}"

    return (
        f"{frontmatter}\n\n"
        f"{BANNER}\n\n"
        f"{aim_heading}\n\n{aim_body}\n\n"
        f"## AIM history\n\n{aim_history_body}\n\n"
        f"## Next step\n\n{next_body}\n\n"
        f"## Sub-goals\n\n{sg_body}\n\n"
        f"## Summary\n\n{summary_body}\n\n"
        f"## Blocked on\n\n{blocked_body}\n\n"
        f"## Prompts\n\n{prompts_body}\n\n"
        f"## Transcript\n\n{transcript_body}\n"
    )


# ---------------------------------------------------------------------------
# ``ccc show``: the card as data, as text
# ---------------------------------------------------------------------------
def phase_of(session: Session) -> str:
    """The card's lifecycle phase: draft, done, parked or running (in that precedence)."""
    if session.draft:
        return PHASE_DRAFT
    if session.done:
        return PHASE_DONE
    if session.status == Status.PARKED.value:
        return PHASE_PARKED
    return PHASE_RUNNING


def build_card(  # pylint: disable=too-many-locals  # one flat record, one place
    store: Store,
    session: Session,
    adapter: ClaudeAdapter,
    git_base: Path,
    *,
    conversation: bool = False,
) -> dict[str, Any]:
    """The session's card as one JSON-ready dict (``ccc show -j``, schema 1).

    Every key is always present (``None`` / ``""`` / ``[]`` when unset) so a consumer
    never probes for one; the draft-only keys (``prompt``, ``start_date``,
    ``start_when``) are ``None`` for a launched session. ``conversation`` holds the
    rendered conversation (the ``ccc peek`` session-tab segments) only when
    *conversation* is set, else ``None``. The observed model is read off the persisted
    transcript-scan row (no transcript read), else probed.
    """
    sid = session.session_id
    history = revisions_for(session, store.list_aim_history(sid))
    subgoals = store.list_subgoals(sid)
    checked, total = store.progress(sid)
    scan = store.get_transcript_scan(sid)
    is_draft = bool(session.draft)
    body: str | None = None
    if conversation:
        body = "".join(text for text, _tag in view_for(adapter, session).segments)
    return {
        "schema_version": SCHEMA_VERSION,
        "session_id": sid,
        "id": display_hash(sid),
        "phase": phase_of(session),
        "status": session.status,
        "archived": bool(session.archived),
        "repo": cwd_to_repo(session.cwd, git_base),
        "cwd": session.cwd,
        "aim": session.aim or "",
        "first_aim": history[0].aim if history else "",
        "short_aim": (history[-1].short_aim if history else "") or session.short_aim or "",
        "aim_history": [
            {"aim": rev.aim, "score": rev.score, "short_aim": rev.short_aim or ""}
            for rev in history
        ],
        "next_step": session.next_step or "",
        "summary": session.summary or "",
        "blocked_on": session.blocked_on or "",
        "subgoals": [{"text": sg.text, "checked": bool(sg.checked)} for sg in subgoals],
        "progress": {"checked": checked, "total": total},
        "job_type": session.job_type or "claude",
        "llm_overseer": session.llm_overseer or DEFAULT_LLM,
        "llm_exec": session.llm_exec or DEFAULT_LLM,
        "model": observed_model_label(adapter, session, scan),
        "effort": session.effort or "",
        "importance": session.importance,
        "deadline": session.deadline or "",
        "depends_on": session.depends_on or "",
        "created": iso_date(session.created_at),
        "last_response": iso_date(session.last_response_at),
        "done_at": iso_date(session.done_at),
        "transcript": str(transcript_path(session)),
        "resume": "" if is_draft else f"c --resume {sid}",
        "prompt": (session.prompt or session.aim or "") if is_draft else None,
        "start_date": (session.start_date or "") if is_draft else None,
        "start_when": (session.start_when or "") if is_draft else None,
        "conversation": body,
    }


def _section(title: str, body: str) -> str:
    """One ``## title`` block; an empty body reads ``(none)`` so no heading dangles."""
    return f"## {title}\n\n{body.strip() or '(none)'}"


def render_text(card: dict[str, Any]) -> str:
    """The human ``ccc show`` view of a :func:`build_card` dict (markdown-ish, no colour)."""
    head = [
        f"{card['id']}  {card['phase']}"
        + (" (archived)" if card["archived"] else "")
        + f"  ·  status {card['status']}",
        f"session      {card['session_id']}",
        f"repo         {card['repo']}",
        f"models       overseer {card['llm_overseer']} · exec {card['llm_exec']}"
        + (f" · observed {card['model']}" if card["model"] else "")
        + (f" · effort {card['effort']}" if card["effort"] else ""),
        f"job type     {card['job_type']}",
    ]
    prog = card["progress"]
    if prog["total"]:
        head.append(f"progress     {prog['checked']}/{prog['total']}")
    for label, key in (
        ("deadline", "deadline"),
        ("depends on", "depends_on"),
        ("created", "created"),
        ("last reply", "last_response"),
        ("done at", "done_at"),
        ("start date", "start_date"),
        ("when", "start_when"),
    ):
        if card[key]:
            head.append(f"{label:<12} {card[key]}")
    revisions = [
        AimRevision(aim=r["aim"], score=r["score"], created_at=0, short_aim=r["short_aim"])
        for r in card["aim_history"]
    ]
    aim_body = card["aim"]
    if card["short_aim"]:
        aim_body = f"{aim_body}\n\n↳ short (current): {card['short_aim']}"
    sg_body = "\n".join(
        f"- [{'x' if sg['checked'] else ' '}] {sg['text']}" for sg in card["subgoals"]
    )
    parts = ["\n".join(head), _section("AIM", aim_body)]
    if card["phase"] == PHASE_DRAFT:
        parts.append(_section("Prompt", card["prompt"] or ""))
    parts += [
        _section("AIM history", render_aim_history(revisions)),
        _section("Next step", card["next_step"]),
        _section("Sub-goals", sg_body),
        _section("Summary", card["summary"]),
        _section("Blocked on", card["blocked_on"]),
    ]
    transcript_body = f"`{card['transcript']}`"
    if card["resume"]:
        transcript_body += f"\n\nResume: `{card['resume']}`"
    parts.append(_section("Transcript", transcript_body))
    if card["conversation"] is not None:
        parts.append(_section("Conversation", card["conversation"]))
    return "\n\n".join(parts) + "\n"
