#!/usr/bin/env python3
"""A session's card, rendered from the store: the ``ccc show`` view and the mirror bodies.

Pure: no vault path, no scrubber, no vouch, nothing written. Two consumers:

* :mod:`command_center.mirrors` serialises its RUNNING/DONE/SESSION documents with
  :func:`serialize_card` / :func:`serialize_session` (lifted here verbatim, so the
  mirror bytes are unchanged; ``mirrors`` re-imports them under their old names).
* ``ccc show`` prints :func:`render_text` (or :func:`build_card` as JSON) for one
  session — the store's facts plus, on request, the full conversation rendered by
  :mod:`command_center.sessionmd` (the segments the ``ccc peek`` session tab shows).
  Same trust level as ``ccc peek``: stdout only, nothing persisted, so no scrub.

The section renderers (:func:`render_prompts`, :func:`render_aim_history`) are
byte-stable: they embed no timestamp, only the session's stable fields.
"""

